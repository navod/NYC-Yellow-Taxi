-- =============================================================================
-- NYC Yellow Taxi warehouse - star schema
--
--   staging : landing area for cleaned rows, reloaded on every pipeline run
--   dw      : dimensional model queried by the dashboard
--
-- Grain of the fact table: one row per completed taxi trip
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS dw;

-- The three small dimensions below each hold a row with key 0 = 'Unknown',
-- so the fact table never needs a NULL foreign key.
CREATE TABLE IF NOT EXISTS dw.dim_vendor (
    vendor_key    SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id     SMALLINT    NOT NULL UNIQUE,      -- TLC VendorID (natural key)
    vendor_name   VARCHAR(60) NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_rate_code (
    rate_code_key   SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_code_id    SMALLINT    NOT NULL UNIQUE,    -- TLC RatecodeID (natural key)
    rate_code_name  VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_payment_type (
    payment_type_key   SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_type_id    SMALLINT    NOT NULL UNIQUE, -- TLC payment_type (natural key)
    payment_type_name  VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_time (
    time_key      SMALLINT    PRIMARY KEY CHECK (time_key BETWEEN 0 AND 23),
    hour_label    VARCHAR(13) NOT NULL,             -- e.g. '17:00 - 17:59'
    day_part      VARCHAR(10) NOT NULL,             -- Night / Morning / Afternoon / Evening
    is_rush_hour  BOOLEAN     NOT NULL
);
