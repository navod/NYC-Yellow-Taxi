-- =============================================================================
-- NYC Yellow Taxi warehouse - star schema
--
--   staging : landing area for cleaned rows, reloaded on every pipeline run
--   dw      : dimensional model queried by the dashboard
--
-- Grain of the fact table: one row per completed taxi trip.
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS dw;

-- ----------------------------------------------------------------- dimensions

-- Calendar dimension. Smart key YYYYMMDD keeps the fact table readable and
-- lets queries filter by date range without joining.
CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key      INTEGER     PRIMARY KEY,          -- e.g. 20230115
    full_date     DATE        NOT NULL UNIQUE,
    year          SMALLINT    NOT NULL,
    quarter       SMALLINT    NOT NULL,
    month         SMALLINT    NOT NULL,
    month_name    VARCHAR(9)  NOT NULL,
    day_of_month  SMALLINT    NOT NULL,
    day_of_week   SMALLINT    NOT NULL,             -- ISO: 1 = Monday ... 7 = Sunday
    day_name      VARCHAR(9)  NOT NULL,
    is_weekend    BOOLEAN     NOT NULL
);

-- Time-of-day dimension at hour grain (24 rows). The key is the hour itself.
CREATE TABLE IF NOT EXISTS dw.dim_time (
    time_key      SMALLINT    PRIMARY KEY CHECK (time_key BETWEEN 0 AND 23),
    hour_label    VARCHAR(13) NOT NULL,             -- e.g. '17:00 - 17:59'
    day_part      VARCHAR(10) NOT NULL,             -- Night / Morning / Afternoon / Evening
    is_rush_hour  BOOLEAN     NOT NULL
);

-- TLC taxi zones. Used twice by the fact table (role-playing dimension):
-- once as the pickup location and once as the drop-off location.
CREATE TABLE IF NOT EXISTS dw.dim_location (
    location_key  SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id   SMALLINT    NOT NULL UNIQUE,      -- TLC LocationID (natural key)
    borough       VARCHAR(50) NOT NULL,
    zone          VARCHAR(100) NOT NULL,
    service_zone  VARCHAR(50) NOT NULL
);

-- The three small dimensions below each hold a row with key 0 = 'Unknown',
-- so the fact table never needs a NULL foreign key.
CREATE TABLE IF NOT EXISTS dw.dim_vendor (
    vendor_key    SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id     SMALLINT    NOT NULL UNIQUE,      -- TLC VendorID (natural key)
    vendor_name   VARCHAR(60) NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_rate_code (
    rate_code_key   SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_code_id    SMALLINT    NOT NULL UNIQUE,    -- TLC RatecodeID (natural key)
    rate_code_name  VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_payment_type (
    payment_type_key   SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_type_id    SMALLINT    NOT NULL UNIQUE, -- TLC payment_type (natural key)
    payment_type_name  VARCHAR(30) NOT NULL
);

-- ----------------------------------------------------------------- fact table

-- Partitioned by month on pickup time:
--   * queries filtered by date only scan the months they need
--   * a pipeline re-run replaces exactly one partition (idempotent loads)
-- Monthly partitions are created by the pipeline (etl/load.py).
CREATE TABLE IF NOT EXISTS dw.fact_taxi_trips (
    trip_id               BIGINT        GENERATED ALWAYS AS IDENTITY,

    -- dimension keys
    pickup_date_key       INTEGER       NOT NULL REFERENCES dw.dim_date (date_key),
    pickup_time_key       SMALLINT      NOT NULL REFERENCES dw.dim_time (time_key),
    pickup_location_key   SMALLINT      NOT NULL REFERENCES dw.dim_location (location_key),
    dropoff_location_key  SMALLINT      NOT NULL REFERENCES dw.dim_location (location_key),
    vendor_key            SMALLINT      NOT NULL REFERENCES dw.dim_vendor (vendor_key),
    rate_code_key         SMALLINT      NOT NULL REFERENCES dw.dim_rate_code (rate_code_key),
    payment_type_key      SMALLINT      NOT NULL REFERENCES dw.dim_payment_type (payment_type_key),

    -- exact timestamps kept on the fact (degenerate attributes)
    pickup_ts             TIMESTAMP     NOT NULL,
    dropoff_ts            TIMESTAMP     NOT NULL,

    -- measures
    passenger_count       SMALLINT,
    trip_distance         NUMERIC(8, 2)  NOT NULL,  -- miles
    trip_duration_minutes NUMERIC(8, 2)  NOT NULL,
    fare_amount           NUMERIC(10, 2) NOT NULL,
    extra                 NUMERIC(10, 2) NOT NULL DEFAULT 0,
    mta_tax               NUMERIC(10, 2) NOT NULL DEFAULT 0,
    tip_amount            NUMERIC(10, 2) NOT NULL DEFAULT 0,
    tolls_amount          NUMERIC(10, 2) NOT NULL DEFAULT 0,
    improvement_surcharge NUMERIC(10, 2) NOT NULL DEFAULT 0,
    congestion_surcharge  NUMERIC(10, 2) NOT NULL DEFAULT 0,
    airport_fee           NUMERIC(10, 2) NOT NULL DEFAULT 0,
    total_amount          NUMERIC(10, 2) NOT NULL,

    -- lineage
    source_file           VARCHAR(100)  NOT NULL,
    loaded_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),

    -- a primary key on a partitioned table must contain the partition column
    PRIMARY KEY (trip_id, pickup_ts)
) PARTITION BY RANGE (pickup_ts);

-- Indexes on the two selective join/filter keys. The other dimension keys have
-- very few distinct values, so an index would not beat a sequential scan.
CREATE INDEX IF NOT EXISTS idx_fact_trips_pickup_date
    ON dw.fact_taxi_trips (pickup_date_key);
CREATE INDEX IF NOT EXISTS idx_fact_trips_pickup_location
    ON dw.fact_taxi_trips (pickup_location_key);

-- -------------------------------------------------------------------- staging

-- UNLOGGED: staging data is disposable, so skipping the write-ahead log
-- makes the bulk COPY noticeably faster.
CREATE UNLOGGED TABLE IF NOT EXISTS staging.stg_trips (
    vendor_id             SMALLINT,
    pickup_ts             TIMESTAMP     NOT NULL,
    dropoff_ts            TIMESTAMP     NOT NULL,
    passenger_count       SMALLINT,
    trip_distance         NUMERIC(8, 2),
    rate_code_id          SMALLINT,
    pickup_location_id    SMALLINT,
    dropoff_location_id   SMALLINT,
    payment_type_id       SMALLINT,
    fare_amount           NUMERIC(10, 2),
    extra                 NUMERIC(10, 2),
    mta_tax               NUMERIC(10, 2),
    tip_amount            NUMERIC(10, 2),
    tolls_amount          NUMERIC(10, 2),
    improvement_surcharge NUMERIC(10, 2),
    congestion_surcharge  NUMERIC(10, 2),
    airport_fee           NUMERIC(10, 2),
    total_amount          NUMERIC(10, 2),
    source_file           VARCHAR(100)  NOT NULL
);

CREATE UNLOGGED TABLE IF NOT EXISTS staging.stg_zones (
    location_id   SMALLINT,
    borough       TEXT,
    zone          TEXT,
    service_zone  TEXT
);

-- ---------------------------------------------------------------------- audit

-- One row per pipeline step attempt: the monitoring trail behind the dashboard.
CREATE TABLE IF NOT EXISTS dw.etl_run_audit (
    audit_id       BIGINT      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    run_id         TEXT        NOT NULL,            -- Airflow run id
    data_month     CHAR(7)     NOT NULL,            -- YYYY-MM being processed
    step           TEXT        NOT NULL,            -- extract / clean / load_fact ...
    status         TEXT        NOT NULL CHECK (status IN ('success', 'failed')),
    started_at     TIMESTAMPTZ NOT NULL,
    finished_at    TIMESTAMPTZ NOT NULL,
    duration_s     NUMERIC(10, 2) NOT NULL,
    rows_in        BIGINT,
    rows_out       BIGINT,
    rows_rejected  BIGINT,
    details        JSONB,                           -- e.g. reject counts per rule
    error_message  TEXT
);

CREATE INDEX IF NOT EXISTS idx_etl_run_audit_run
    ON dw.etl_run_audit (run_id, started_at);
